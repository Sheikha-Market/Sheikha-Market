#!/usr/bin/env node

const fs = require('node:fs');
const path = require('node:path');

const rootDir = path.resolve(__dirname, '..');
const configPath = path.join(rootDir, 'config', 'sheikha-unicode-smart-architecture.json');
const outputPath = path.join(rootDir, 'docs', 'sheikha-architecture.generated.mmd');

function loadArchitectureConfig() {
    const raw = fs.readFileSync(configPath, 'utf8');
    return JSON.parse(raw);
}

function sanitizeId(value) {
    return (
        String(value || '')
            .toLowerCase()
            .replace(/[^a-z0-9_]/g, '_')
            .replace(/_+/g, '_')
            .replace(/^_|_$/g, '') || 'node'
    );
}

function buildMermaid(architecture) {
    const data = architecture.data || {};
    const systems = Array.isArray(data.systems) ? data.systems : [];

    const lines = [];
    lines.push('%% Auto-generated by scripts/generate-sheikha-architecture-mermaid.js');
    lines.push('flowchart TD');
    lines.push('    GOV["Governance\\nArabic-First + UTF-8 Strict"]');
    lines.push('    HW["Hardware Layer"]');
    lines.push('    SW["Software & Data Layer"]');
    lines.push('    NET["Networking Layer"]');
    lines.push('    GOV --> HW');
    lines.push('    GOV --> SW');
    lines.push('    GOV --> NET');

    systems.forEach(service => {
        const nodeId = sanitizeId(service.id || service.title);
        const title = String(service.title || service.id || 'Unknown Service').replace(/"/g, '\\"');
        const role = String(service.role || 'service').replace(/"/g, '\\"');
        lines.push(`    ${nodeId}["${title}\\n(${role})"]`);
        lines.push(`    SW --> ${nodeId}`);
    });

    return `${lines.join('\n')}\n`;
}

function main() {
    const architecture = loadArchitectureConfig();
    const mermaid = buildMermaid(architecture);

    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, mermaid, 'utf8');

    console.log('Mermaid diagram generated successfully.');
    console.log(`Output: ${outputPath}`);
}

main();
