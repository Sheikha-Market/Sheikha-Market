class SheikhaIslamicMarketsEngine {
    getOverview() {
        return {
            بسم_الله: 'بسم الله الرحمن الرحيم',
            phase: 32,
            name: 'رقمنة الأسواق الإسلامية الكونية',
            verse: '﴿وَأَحَلَّ اللَّهُ الْبَيْعَ وَحَرَّمَ الرِّبَا﴾',
            core_mission: 'من سوق آدم إلى سوق شيخة — موحَّدة بالكتاب والسنة',
            hadith: '«هذا سوقكم — لا يضيق عليكم ولا يؤخذ منكم فيه خراج» — النبي ﷺ',
            stats: DIGITIZATION_STATS,
            charter: SHEIKHA_MARKET_CHARTER,
            timestamp: new Date().toISOString(),
        };
    }

    getProphetsMarkets()        { return PROPHETS_MARKETS; }
    getPreIslamicMarkets()      { return PRE_ISLAMIC_ARAB_MARKETS; }
    getProphetEraMarkets()      { return PROPHET_MARKETS; }
    getRashideenMarkets()       { return RASHIDEEN_MARKETS; }
    getHistoricalMarkets()      { return ISLAMIC_HISTORICAL_MARKETS; }
    getForeignInteractions()    { return FOREIGN_MARKETS_INTERACTION; }
    getCharter()                { return SHEIKHA_MARKET_CHARTER; }
    getStats()                  { return DIGITIZATION_STATS; }

    getMadinahMarket() {
        return PROPHET_MARKETS.find(m => m.id === 'madinah_market');
    }

    getTimeline() {
        return [
            ...PROPHETS_MARKETS.map(m => ({ ...m, era_type: 'نبوة' })),
            ...PRE_ISLAMIC_ARAB_MARKETS.map(m => ({ ...m, era_type: 'جاهلية' })),
            ...PROPHET_MARKETS.map(m => ({ ...m, era_type: 'عهد النبي ﷺ' })),
            ...RASHIDEEN_MARKETS.map(m => ({ ...m, era_type: 'الخلفاء الراشدون' })),
            ...ISLAMIC_HISTORICAL_MARKETS.map(m => ({ ...m, era_type: 'تاريخ إسلامي' })),
        ];
    }

    searchMarket(query) {
        if (!query) return [];
        const q = query.toLowerCase();
        const all = [
            ...PROPHETS_MARKETS, ...PRE_ISLAMIC_ARAB_MARKETS,
            ...PROPHET_MARKETS, ...RASHIDEEN_MARKETS,
            ...ISLAMIC_HISTORICAL_MARKETS, ...FOREIGN_MARKETS_INTERACTION,
        ];
        return all.filter(m =>
            JSON.stringify(m).toLowerCase().includes(q)
        );
    }
}

module.exports = new SheikhaIslamicMarketsEngine();
