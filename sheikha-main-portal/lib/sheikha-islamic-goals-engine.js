class SheikhaIslamicGoalsEngine {
    getOverview() {
        return {
            بسم_الله: 'بسم الله الرحمن الرحيم',
            phase: 28,
            name: 'الأهداف الإسلامية الشاملة لمنظومة شيخة',
            supreme_purpose: 'توحيد الله — خدمة الأمة — إعمار الدنيا — الفوز بالآخرة',
            verse: '﴿كُنتُمْ خَيْرَ أُمَّةٍ أُخْرِجَتْ لِلنَّاسِ﴾',
            goals_count: SUPREME_GOALS.length,
            progress: GOALS_PROGRESS,
            categories: [...new Set(SUPREME_GOALS.map(g => g.category))],
            timestamp: new Date().toISOString(),
        };
    }
    getGoals(category)   { return category ? SUPREME_GOALS.filter(g => g.category === category) : SUPREME_GOALS; }
    getGoal(id)          { return SUPREME_GOALS.find(g => g.id === id) || null; }
    getProgress()        { return GOALS_PROGRESS; }
    getKPIs()            { return SUPREME_GOALS.map(g => ({ goal: g.name, icon: g.icon, ...g.kpi })); }
    getTopGoal()         { return SUPREME_GOALS.find(g => g.rank === 1); }
    getCategoryMap() {
        const map = {};
        for (const g of SUPREME_GOALS) {
            if (!map[g.category]) map[g.category] = [];
            map[g.category].push({ id: g.id, name: g.name, icon: g.icon, rank: g.rank, status: g.status });
        }
        return map;
    }
}

module.exports = new SheikhaIslamicGoalsEngine();
