'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { once } = require('node:events');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '/tmp/sheikha-architecture-tools/node_modules/playwright');
const { createWorkspaceServer } = require('../tools/preview/sheikha-workspace-preview.cjs');
const output = path.join(__dirname, '../runtime/industrial-planner-verification');

test('industrial planning works on desktop and mobile with downloads, research boundaries and failure recovery', { timeout: 90000 }, async t => {
  const server = createWorkspaceServer(); server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const base = `http://127.0.0.1:${server.address().port}`;
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/opt/google/chrome/chrome',
    headless: true, args: ['--no-sandbox'] });
  t.after(async () => { await browser.close(); await new Promise(resolve => { server.closeAllConnections(); server.close(resolve); }); });
  fs.mkdirSync(output, { recursive: true });
  const errors = [], outside = [];
  for (const viewport of [{ width: 1440, height: 960 }, { width: 390, height: 844 }, { width: 320, height: 740 }]) {
    const context = await browser.newContext({ viewport, acceptDownloads: true });
    const page = await context.newPage();
    page.on('pageerror', err => errors.push(err.message));
    page.on('request', req => { if (!req.url().startsWith(base) && !req.url().startsWith('blob:')) outside.push(req.url()); });
    await page.goto(base + '/workspace/');
    await page.getByRole('link', { name: 'العناقيد الصناعية', exact: true }).click();
    await page.locator('#industry-content').waitFor({ state: 'visible' });
    await page.keyboard.press('Tab');
    assert.equal(await page.locator('.skip').evaluate(el => el === document.activeElement), true);
    assert.equal(await page.locator('#industry-sectors button').count(), 12);
    await page.locator('#industry-search').fill('does-not-exist');
    assert.equal(await page.locator('#industry-sectors button').count(), 0);
    assert.equal(await page.locator('#industry-empty').isVisible(), true);
    await page.locator('#industry-search').fill('robot');
    assert.equal(await page.locator('#industry-sectors button').count(), 1);
    await page.locator('[data-sector="robotics"]').click();
    assert.equal(await page.locator('#plan-template').inputValue(), 'robotics');
    await page.locator('#plan-type').selectOption('farm');
    assert.equal(await page.locator('#plan-template option[value="robotics"]').count(), 0);
    assert.equal(await page.locator('#plan-template').inputValue(), 'food');
    await page.locator('#industry-search').fill('');
    await page.locator('[data-sector="space"]').click();
    assert.equal(await page.locator('#plan-horizon').inputValue(), 'space-research');
    assert.equal(await page.locator('#plan-horizon').isDisabled(), true);
    await page.locator('#plan-name').fill('مجمع شيخة <script>window.UNSAFE=1</script>');
    await page.locator('#plan-quantity').fill('101');
    await page.locator('#plan-days').fill('30');
    await page.locator('#plan-share').fill('10');
    await page.locator('#plan-submit').click();
    assert.equal(await page.locator('#industry-result').isVisible(), false);
    await page.locator('#plan-consent').check();
    await page.locator('#plan-submit').click();
    await page.locator('#industry-result').waitFor({ state: 'visible' });
    assert.equal(await page.evaluate(() => window.UNSAFE), undefined);
    const plan = JSON.parse(await page.locator('#industry-json').textContent());
    assert.equal(plan.output, 'حزمة دراسة بحثية فقط');
    assert.equal(plan.targets.dailyTargetUnits, 4); assert.equal(plan.targets.communityUnits, 10);
    assert.equal(plan.boundaries.productionReady, false);
    assert.equal(plan.monitoring.watch.state, 'PROPOSED_NOT_SCHEDULED');
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: 'تنزيل المسودة JSON' }).click();
    const download = await downloadPromise;
    assert.deepEqual(JSON.parse(fs.readFileSync(await download.path(), 'utf8')), plan);
    await page.evaluate(async () => { await Promise.all([...document.images].filter(img => img.getClientRects().length).map(img => img.decode())); });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `overflow ${viewport.width}`);
    assert.deepEqual(await page.locator('button:visible').evaluateAll(items => items.filter(el => el.scrollWidth > el.clientWidth + 1).map(el => el.textContent)), []);
    assert.deepEqual(await page.locator('.topbar nav a').evaluateAll(items => items.filter(el => el.scrollWidth > el.clientWidth + 1).map(el => el.textContent)), []);
    await page.locator('#plan-name').fill('عنقود شيخة للبحوث الصناعية النافعة');
    await page.locator('#plan-submit').click();
    await page.locator('#industry-result').waitFor({ state: 'visible' });
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: path.join(output, `industrial-plan-${viewport.width}.png`), fullPage: true });
    await page.screenshot({ path: path.join(output, `industrial-viewport-${viewport.width}.png`) });

    await page.locator('#plan-name').fill('مسودة محدثة');
    assert.equal(await page.locator('#industry-result').isVisible(), false);
    await page.route('**/industry/plan', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{}' }));
    await page.locator('#plan-submit').click();
    await page.waitForFunction(() => document.getElementById('plan-status').classList.contains('error'));
    assert.equal(await page.locator('#industry-result').isVisible(), false);
    assert.equal(await page.locator('#plan-submit').isEnabled(), true);
    await page.unroute('**/industry/plan');
    await page.locator('[data-sector="metals"]').click();
    await page.locator('#plan-horizon').selectOption('earth');
    await page.locator('#plan-submit').click();
    await page.locator('#industry-result').waitFor({ state: 'visible' });
    assert.equal(JSON.parse(await page.locator('#industry-json').textContent()).output, 'دفعة مواد مطابقة لمواصفات مقترحة');
    await page.reload();
    await page.locator('#industry-content').waitFor({ state: 'visible' });
    assert.equal(await page.locator('#industry-result').isVisible(), false);
    await page.route('**/industry/catalog', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{}' }));
    await page.reload(); await page.locator('#industry-load-error').waitFor({ state: 'visible' });
    await page.unroute('**/industry/catalog');
    await page.locator('#industry-retry').click(); await page.locator('#industry-content').waitFor({ state: 'visible' });
    await context.close();
  }
  assert.deepEqual(errors, []); assert.deepEqual(outside, []);
  fs.writeFileSync(path.join(output, 'browser-verification.json'), JSON.stringify({
    checkedAt: new Date().toISOString(), widths: [1440, 390, 320], passed: true, errors, outside
  }, null, 2));
});
