'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createHash } = require('node:crypto');
const { once } = require('node:events');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '/tmp/sheikha-architecture-tools/node_modules/playwright');
const { createWorkspaceServer } = require('../tools/preview/sheikha-workspace-preview.cjs');
const { createAssetDigitization, SOURCE_DEFINITIONS } = require('../core/ownership/sheikha-asset-digitization-v1.cjs');
const output = path.join(__dirname, '../runtime/asset-digitization-verification');
test('digital passports, architecture, gates, evidence and failure recovery work on desktop and mobile without mutations', { timeout: 90000 }, async t => {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'sheikha-asset-browser-'));
  t.after(() => fs.rmSync(temp, { recursive: true, force: true })); fs.mkdirSync(output, { recursive: true });
  const sourcePaths = Object.fromEntries(SOURCE_DEFINITIONS.map(([id]) => [id, path.join(temp, id)]));
  for (const [id, , , kind] of SOURCE_DEFINITIONS) fs.writeFileSync(sourcePaths[id], kind === 'json' ? '{}' : 'SECRET_SOURCE_NOT_FOR_DISPLAY');
  const write = (id, value) => fs.writeFileSync(sourcePaths[id], JSON.stringify(value));
  write('mvp-requirements', { scope: 'DESIGN_ONLY' }); write('mvp-interfaces', { contracts: Array(3).fill({ implementation: 'NOT_IMPLEMENTED' }) });
  write('mvp-manifest', { authority_granted: false, payments_authorized: false, physical_actuation: false,
    production_enabled: false, decision: 'DESIGN_ONLY_HOLD', files_sha256: Object.fromEntries(
      ['requirements', 'architecture', 'interfaces', 'tests'].map(n => [n + '.json', createHash('sha256').update(fs.readFileSync(sourcePaths['mvp-' + n])).digest('hex')])) });
  const options = { sourcePaths, root: path.join(temp, 'reports'), now: () => 1792548000000 };
  const report = createAssetDigitization(options).inspect(), before = Object.values(sourcePaths).map(p => fs.readFileSync(p, 'utf8'));
  const server = createWorkspaceServer({ assets: options }); server.listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(() => new Promise(resolve => { server.closeAllConnections(); server.close(resolve); }));
  const base = `http://127.0.0.1:${server.address().port}`;
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/opt/google/chrome/chrome', headless: true, args: ['--no-sandbox'] });
  t.after(() => browser.close()); const errors = [], outside = [], mutations = [];
  for (const width of [1440, 390, 320]) {
    const context = await browser.newContext({ viewport: { width, height: 900 }, acceptDownloads: true });
    try {
      const page = await context.newPage(); page.setDefaultTimeout(10000);
      page.on('pageerror', error => errors.push(error.message));
      page.on('request', req => {
        if (!req.url().startsWith(base) && !req.url().startsWith('blob:')) outside.push(req.url());
        if (!['GET', 'HEAD'].includes(req.method())) mutations.push(req.url());
      });
      await page.goto(base + '/workspace/assets.html');
      const ready = () => page.waitForFunction(() => !document.getElementById('asset-export').disabled);
      const layout = async () => {
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `page overflow at ${width}`);
        assert.deepEqual(await page.locator('button:visible,th:visible,td:visible').evaluateAll(items => items.filter(e => e.scrollWidth > e.clientWidth + 1).map(e => e.textContent)), []);
      };
      await ready(); assert.equal(await page.locator('[data-asset]').count(), 6);
      assert.equal(await page.locator('.asset-panorama img').evaluate(img => img.complete && img.naturalWidth > 0), true);
      await layout(); await page.screenshot({ path: path.join(output, `assets-${width}.png`) });
      assert.equal(await page.locator('#asset-inventory-scope').isVisible(), true);
      await page.locator('#asset-inventory-scope summary').click();
      assert.equal(await page.locator('[data-scope-category]').count(), 6);
      for (const id of ['licenses', 'equipment', 'visuals']) assert.ok((await page.locator(`[data-scope-category="${id}"]`).textContent()).includes('قائمة الأصول التفصيلية لم تُقدّم'));
      assert.ok((await page.locator('[data-scope-category="domains"]').textContent()).includes('sheikha.top'));
      await layout(); await page.locator('#asset-inventory-scope').scrollIntoViewIfNeeded();
      await page.screenshot({ path: path.join(output, `inventory-scope-${width}.png`) });
      await page.locator('#asset-inventory-scope summary').click();
      await page.locator('#asset-kind').selectOption('DOMAIN'); assert.equal(await page.locator('[data-asset]').count(), 2);
      await page.locator('#asset-search').fill('NO_MATCH'); assert.equal(await page.locator('#asset-empty').isVisible(), true);
      await page.locator('#asset-search').fill(''); await page.locator('#asset-kind').selectOption('DESIGN_PACKAGE');
      await page.locator('[data-asset="supplier-package"] button').click();
      assert.equal(await page.locator('#passport-title').textContent(), 'حزمة تصميم بوابة الموردين');
      assert.equal(await page.locator('#passport-lab').isVisible(), true);
      assert.equal(await page.locator('#passport-lab').getAttribute('href'), './supplier-lab.html');
      assert.ok((await page.locator('#passport-facts').textContent()).includes('الإنتاج متوقف'));
      let downloading = page.waitForEvent('download'); await page.locator('#passport-export').click();
      let file = await downloading, passport = JSON.parse(fs.readFileSync(await file.path(), 'utf8'));
      assert.equal(passport.asset.id, 'supplier-package'); assert.equal(passport.asset.productionEnabled, false); assert.equal(passport.sources.length, 5);
      downloading = page.waitForEvent('download'); await page.locator('#asset-export').click(); file = await downloading;
      assert.deepEqual(JSON.parse(fs.readFileSync(await file.path(), 'utf8')), report);
      await page.locator('#passport-plan').click();
      assert.equal(await page.locator('#tab-plan').getAttribute('aria-selected'), 'true');
      assert.equal(await page.locator('#requirement-asset').inputValue(), 'supplier-package');
      assert.equal(await page.locator('[data-requirement="supplier-package--scope"]').getAttribute('open'), '');
      assert.equal(await page.locator('.asset-requirement').count(), 13);
      await page.locator('#requirement-search').fill('/api/suppliers'); assert.equal(await page.locator('.asset-requirement').count(), 1);
      await page.locator('.asset-requirement summary').click();
      assert.ok((await page.locator('.asset-requirement').textContent()).includes('قبول غير مختبر'));
      await page.locator('.asset-requirement a').first().click();
      assert.equal(await page.locator('#requirement-search').inputValue(), '');
      assert.equal(await page.locator('[data-requirement="supplier-package--scope"]').getAttribute('open'), '');
      await layout(); await page.screenshot({ path: path.join(output, `requirement-detail-${width}.png`) });
      await page.locator('[data-requirement="supplier-package--scope"] summary').click();
      await page.locator('#panel-plan').evaluate(panel => panel.scrollIntoView({ block: 'start' })); await layout();
      await page.screenshot({ path: path.join(output, `requirements-${width}.png`) });
      await page.locator('#requirement-asset').selectOption(''); await page.locator('#requirement-status').selectOption('REVIEW_REQUIRED');
      assert.equal(await page.locator('.asset-requirement').count(), 48);
      await page.locator('#requirement-status').selectOption('LOCAL_PASS');
      assert.equal(await page.locator('.asset-requirement').count(), report.executionPlan.summary.localChecksPassed);
      await page.locator('#requirement-search').fill('NO_MATCH'); assert.equal(await page.locator('#requirement-empty').isVisible(), true);
      downloading = page.waitForEvent('download'); await page.locator('#plan-export').click(); file = await downloading;
      const exportedPlan = JSON.parse(fs.readFileSync(await file.path(), 'utf8'));
      assert.deepEqual(exportedPlan.plan, report.executionPlan); assert.equal(exportedPlan.parentDossierDigest, report.integrity.digest);
      assert.equal(exportedPlan.policy.productionEnabled, false); assert.equal(exportedPlan.plan.requirements.length, 66);
      await page.locator('#requirement-search').fill(''); await page.locator('#requirement-status').selectOption('');
      await page.locator('#tab-architecture').click(); assert.equal(await page.locator('#asset-layers li').count(), 5); await layout();
      await page.locator('#panel-architecture').scrollIntoViewIfNeeded(); await page.screenshot({ path: path.join(output, `architecture-${width}.png`) });
      await page.locator('#tab-architecture').focus(); await page.keyboard.press('ArrowLeft');
      assert.equal(await page.locator('#tab-readiness').getAttribute('aria-selected'), 'true'); assert.equal(await page.locator('#asset-gates .asset-gate').count(), 8); await layout();
      await page.locator('#tab-evidence').click(); assert.equal(await page.locator('[data-source]').count(), 11);
      assert.ok((await page.locator('#asset-package').textContent()).includes('3 من 3'));
      assert.ok((await page.locator('#asset-duplicates').textContent()).includes('1 محتويات مستقلة'));
      assert.equal((await page.content()).includes('SECRET_SOURCE_NOT_FOR_DISPLAY'), false); await layout();
      await page.locator('#panel-evidence').scrollIntoViewIfNeeded(); await page.screenshot({ path: path.join(output, `evidence-${width}.png`) });
      await page.route('**/assets/report', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{}' }));
      await page.locator('#asset-refresh').click(); await page.waitForFunction(() => !document.getElementById('asset-refresh').disabled);
      assert.equal(await page.locator('#asset-export').isDisabled(), true); assert.equal(await page.locator('#asset-content').isVisible(), false);
      assert.equal(await page.locator('#asset-json').textContent(), '');
      assert.equal(await page.locator('#plan-export').isDisabled(), true); assert.equal(await page.locator('.asset-requirement').count(), 0);
      assert.equal(await page.locator('[data-scope-category]').count(), 0); assert.equal(await page.locator('#asset-inventory-scope').isVisible(), false);
      await page.unroute('**/assets/report'); await page.locator('#asset-refresh').click(); await ready();
      const bytes = fs.readFileSync(sourcePaths['host-source']); fs.unlinkSync(sourcePaths['host-source']);
      await page.locator('#asset-refresh').click(); await ready();
      assert.ok((await page.locator('[data-source="host-source"]').textContent()).includes('ملف غير متاح'));
      fs.writeFileSync(sourcePaths['host-source'], bytes); await page.reload(); await ready();
      const historical = structuredClone(report); delete historical.executionPlan; delete historical.inventoryScope;
      await page.route('**/assets/report', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(historical) }));
      await page.locator('#tab-plan').click(); await page.locator('#asset-refresh').click(); await ready();
      assert.equal(await page.locator('#tab-plan').isVisible(), false); assert.equal(await page.locator('#passport-plan').isVisible(), false);
      assert.equal(await page.locator('#asset-inventory-scope').isVisible(), false); assert.equal(await page.locator('[data-scope-category]').count(), 0);
      assert.equal(await page.locator('#plan-export').isDisabled(), true); assert.equal(await page.locator('.asset-requirement').count(), 0);
      assert.equal(await page.locator('#tab-register').getAttribute('aria-selected'), 'true');
      await page.locator('#tab-readiness').focus(); await page.keyboard.press('ArrowLeft');
      assert.equal(await page.locator('#tab-evidence').getAttribute('aria-selected'), 'true');
      await page.unroute('**/assets/report'); await page.locator('#asset-refresh').click(); await ready();
      assert.equal(await page.locator('#tab-plan').isVisible(), true);
      const untrusted = structuredClone(report); untrusted.assets[0].name = '<img src=x onerror=alert(1)>';
      await page.route('**/assets/report', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(untrusted) }));
      await page.locator('#asset-refresh').click(); await ready(); await page.locator('#tab-register').click();
      await page.locator('#asset-kind').selectOption('');
      assert.equal(await page.locator('[data-asset="domain-core"] img[src=x]').count(), 0);
      assert.ok((await page.locator('[data-asset="domain-core"]').textContent()).includes('<img src=x onerror=alert(1)>'));
    } finally { await context.close(); }
  }
  assert.deepEqual(Object.values(sourcePaths).map(p => fs.readFileSync(p, 'utf8')), before);
  assert.equal(fs.existsSync(options.root), false); assert.deepEqual(errors, []); assert.deepEqual(outside, []); assert.deepEqual(mutations, []);
  fs.writeFileSync(path.join(output, 'browser-verification.json'), JSON.stringify({ checkedAt: new Date().toISOString(), widths: [1440, 390, 320],
    errors, outside, mutations, sourcesUnchanged: true, filtersAndExports: true, requirementTraceability: true, failureRecovery: true, passed: true }, null, 2));
});
