#!/usr/bin/env python3
"""
مترجم لغة شيخة البرمجية إلى نواة شيخة-رست (Sheikha Language to Sheikha-Rust Compiler - shk-rustc v2.0.0)
يقرأ ملفات (.shk) المكتوبة بلغة شيخة البرمجية، ويتحقق من ميثاق الحوكمة،
ويولّد شفرة Rust العتادية الكاملة باسم وهوية وواجهة استدعاء شيخة (SHEIKHA_LANGUAGE_NATIVE_ABI_V2).
"""
import hashlib, json, os, re, sys, time

def compile_shk_to_sheikha_rust(shk_path, rs_out_path, manifest_out_path):
    with open(shk_path, "r", encoding="utf-8") as f:
        shk_source = f.read()

    if "BOUND_BY_QURAN_SUNNAH" not in shk_source:
        raise ValueError("[SHK-RUSTC ERROR] ميثاق الحوكمة BOUND_BY_QURAN_SUNNAH مفقود من مصدر لغة شيخة!")

    shk_sha256 = hashlib.sha256(shk_source.encode("utf-8")).hexdigest()

    # استخراج جميع جمل اطبع_برهان("...") من مصدر لغة شيخة (.shk)
    print_statements = re.findall(r'اطبع_برهان\("([^"]+)"\);', shk_source)

    rust_lines = [
        "// ============================================================================",
        "// AUTO-GENERATED BY SHEIKHA LANGUAGE COMPILER (shk-rustc v2.0.0)",
        f"// Source File: {os.path.basename(shk_path)}",
        f"// Source SHA-256: {shk_sha256}",
        "// Language ABI: SHEIKHA_LANGUAGE_NATIVE_ABI_V2",
        "// Governance: BOUND_BY_QURAN_SUNNAH",
        "// ============================================================================",
        "#![no_std]",
        "#![no_main]",
        "",
        "use core::fmt::{self, Write};",
        "use core::panic::PanicInfo;",
        "",
        "// تعريفات لغة شيخة القياسية فوق محرك Rust (Sheikha-Rust Sovereign Types)",
        "pub type SheikhaPortAddress = u16;",
        "pub type SheikhaMemAddress = *mut u8;",
        "pub type SheikhaMeasure = usize;",
        "pub type SheikhaByte = u8;",
        "",
        "const SHEIKHA_COM1_PORT: SheikhaPortAddress = 0x3F8;",
        "const SHEIKHA_VGA_BUFFER: SheikhaMemAddress = 0xB8000 as SheikhaMemAddress;",
        "const SHEIKHA_VGA_WIDTH: SheikhaMeasure = 80;",
        "const SHEIKHA_VGA_HEIGHT: SheikhaMeasure = 25;",
        "",
        "#[inline]",
        "unsafe fn sheikha_outb(port: SheikhaPortAddress, val: SheikhaByte) {",
        '    core::arch::asm!("out dx, al", in("dx") port, in("al") val, options(nomem, nostack, preserves_flags));',
        "}",
        "",
        "#[no_mangle]",
        'pub extern "C" fn sheikha_init_serial_burhan() {',
        "    unsafe {",
        "        sheikha_outb(SHEIKHA_COM1_PORT + 1, 0x00);",
        "        sheikha_outb(SHEIKHA_COM1_PORT + 3, 0x80);",
        "        sheikha_outb(SHEIKHA_COM1_PORT + 0, 0x03);",
        "        sheikha_outb(SHEIKHA_COM1_PORT + 1, 0x00);",
        "        sheikha_outb(SHEIKHA_COM1_PORT + 3, 0x03);",
        "        sheikha_outb(SHEIKHA_COM1_PORT + 2, 0xC7);",
        "        sheikha_outb(SHEIKHA_COM1_PORT + 4, 0x0B);",
        "    }",
        "}",
        "",
        "#[repr(C)]",
        "pub struct SheikhaSovereignConsole {",
        "    row: SheikhaMeasure,",
        "    col: SheikhaMeasure,",
        "    color: SheikhaByte,",
        "}",
        "",
        "impl SheikhaSovereignConsole {",
        "    pub const fn new(fg: SheikhaByte, bg: SheikhaByte) -> Self {",
        "        Self { row: 0, col: 0, color: (bg << 4) | (fg & 0x0F) }",
        "    }",
        "    pub fn clear_screen(&mut self) {",
        "        for r in 0..SHEIKHA_VGA_HEIGHT {",
        "            for c in 0..SHEIKHA_VGA_WIDTH {",
        "                let offset = (r * SHEIKHA_VGA_WIDTH + c) * 2;",
        "                unsafe {",
        "                    *SHEIKHA_VGA_BUFFER.add(offset) = b' ';",
        "                    *SHEIKHA_VGA_BUFFER.add(offset + 1) = self.color;",
        "                }",
        "            }",
        "        }",
        "        self.row = 0;",
        "        self.col = 0;",
        "    }",
        "    pub fn write_burhan_byte(&mut self, byte: SheikhaByte) {",
        "        unsafe { sheikha_outb(SHEIKHA_COM1_PORT, byte); }",
        "        match byte {",
        "            b'\\n' => {",
        "                self.col = 0;",
        "                if self.row + 1 < SHEIKHA_VGA_HEIGHT { self.row += 1; }",
        "            }",
        "            byte => {",
        "                if self.col >= SHEIKHA_VGA_WIDTH {",
        "                    self.col = 0;",
        "                    if self.row + 1 < SHEIKHA_VGA_HEIGHT { self.row += 1; }",
        "                }",
        "                let offset = (self.row * SHEIKHA_VGA_WIDTH + self.col) * 2;",
        "                unsafe {",
        "                    *SHEIKHA_VGA_BUFFER.add(offset) = byte;",
        "                    *SHEIKHA_VGA_BUFFER.add(offset + 1) = self.color;",
        "                }",
        "                self.col += 1;",
        "            }",
        "        }",
        "    }",
        "}",
        "",
        "impl Write for SheikhaSovereignConsole {",
        "    fn write_str(&mut self, s: &str) -> fmt::Result {",
        "        for byte in s.bytes() { self.write_burhan_byte(byte); }",
        "        Ok(())",
        "    }",
        "}",
        "",
        "/// الدالة السيادية المولدة مباشرة من دالة_سيادية منطق_نواة_شيخة_الأصيل() في ملف .shk",
        "#[no_mangle]",
        'pub extern "C" fn sheikha_language_kernel_entry() {',
        "    sheikha_init_serial_burhan();",
        "    let mut console = SheikhaSovereignConsole::new(0x0A, 0x00);",
        "    console.clear_screen();",
    ]

    for stmt in print_statements:
        rust_lines.append(f'    let _ = writeln!(console, "{stmt}");')

    rust_lines.append(f'    let _ = writeln!(console, "language_source_sha256={shk_sha256}");')

    rust_lines.extend([
        "}",
        "",
        "/// نقطة الإقلاع العتادية المربوطة بعقد لغة شيخة (SHEIKHA_LANGUAGE_BOOT_CONTRACT_V2)",
        "#[no_mangle]",
        'pub extern "C" fn _start() -> ! {',
        "    sheikha_language_kernel_entry();",
        "    loop {",
        '        unsafe { core::arch::asm!("hlt", options(nomem, nostack, preserves_flags)); }',
        "    }",
        "}",
        "",
        "#[panic_handler]",
        "fn panic(info: &PanicInfo) -> ! {",
        "    let mut err_console = SheikhaSovereignConsole::new(0x0F, 0x04);",
        '    let _ = writeln!(err_console, "\\n[SHEIKHA LANGUAGE KERNEL PANIC]: {}", info);',
        "    loop {",
        '        unsafe { core::arch::asm!("cli; hlt", options(nomem, nostack)); }',
        "    }",
        "}",
    ])

    generated_rust = "\n".join(rust_lines) + "\n"
    with open(rs_out_path, "w", encoding="utf-8") as out:
        out.write(generated_rust)

    rs_sha256 = hashlib.sha256(generated_rust.encode("utf-8")).hexdigest()

    manifest = {
        "compiler": "Sheikha-Rust Sovereign Compiler (shk-rustc v2.0.0)",
        "owner": "مؤسسة سلمان أحمد بن سلمان الراجح للتجارة (CR: 2051263653)",
        "governance": "BOUND_BY_QURAN_SUNNAH",
        "source_language": "Sheikha Programming Language (.shk)",
        "target_engine": "Sheikha-Rust Bare-Metal Kernel (x86_64)",
        "shk_source_file": shk_path,
        "shk_source_sha256": shk_sha256,
        "generated_rust_file": rs_out_path,
        "generated_rust_sha256": rs_sha256,
        "abi_contract": "SHEIKHA_LANGUAGE_NATIVE_ABI_V2",
        "statements_transpiled": len(print_statements),
        "compiled_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    }
    with open(manifest_out_path, "w", encoding="utf-8") as mf:
        json.dump(manifest, mf, ensure_ascii=False, indent=2)

    print(json.dumps(manifest, ensure_ascii=False, indent=2))

if __name__ == "__main__":
    shk_in = sys.argv[1] if len(sys.argv) > 1 else "sheikha-language/kernel/sheikha_kernel.shk"
    rs_out = sys.argv[2] if len(sys.argv) > 2 else "bare-metal/sheikha-kernel-rs/src/main.rs"
    mf_out = "sheikha-language/kernel/sheikha_rustc_manifest.json"
    compile_shk_to_sheikha_rust(shk_in, rs_out, mf_out)
